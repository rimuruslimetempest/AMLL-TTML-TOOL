function pack(theme: Omit<ThemeManifest, "format" | "author" | "version"> & {
	css?: string;
}): ThemePack {
	return {
		format: 1,
		author: AUTHOR,
		version: VERSION,
		...theme,
		builtin: true,
	};
}

