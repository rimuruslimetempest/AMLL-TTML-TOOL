function scheme(
	id: string,
	name: string,
	appearance: "dark" | "light",
	overrides: Partial<ThemeTokenValues> = {},
	flatTokens?: Partial<ThemeTokenValues>,
): ThemeScheme {
	return {
		id,
		name,
		appearance,
		tokens: {
			...(appearance === "dark" ? DEFAULT_DARK : DEFAULT_LIGHT),
			...overrides,
		},
		...(flatTokens ? { flatTokens } : {}),
	};
}

